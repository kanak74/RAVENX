import { jsPDF } from 'jspdf'
import type { AssessmentReport } from '../features/symptom-check/types'

export interface MlPredictionItem {
  condition: string
  confidencePercent: number
  summary: string
  recommendedSpecialist: string
  influencingSymptoms: { id: string; label: string; weight: number }[]
}

export function downloadAssessmentPdf(
  report: AssessmentReport,
  mlPredictions: MlPredictionItem[],
  patientName?: string,
) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const margin = 44
  const maxWidth = 507
  let y = 50

  const addLine = (text: string, size = 10, bold = false, color: [number, number, number] = [24, 32, 30]) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal')
    doc.setFontSize(size)
    doc.setTextColor(...color)
    const lines = doc.splitTextToSize(text, maxWidth) as string[]
    for (const line of lines) {
      if (y > 770) {
        doc.addPage()
        y = 50
      }
      doc.text(line, margin, y)
      y += size * 1.45
    }
  }

  addLine('VITALORA — Health Assessment Report', 18, true, [23, 75, 66])
  addLine('Understand your symptoms. Know your next step.', 10, false, [110, 117, 111])
  addLine(`Generated: ${new Date().toLocaleString()}${patientName ? ` · Patient: ${patientName}` : ''}`, 9, false, [110, 117, 111])
  y += 10

  addLine('1. Care Guidance Level', 12, true, [23, 75, 66])
  addLine(report.careGuidance.label, 11, true)
  addLine(report.careGuidance.summary, 10)
  y += 8

  addLine('2. Reported Symptoms & Context', 12, true, [23, 75, 66])
  addLine(
    `Symptoms: ${report.reportedSymptoms.confirmedSymptomLabels.join(', ') || 'None selected'
    }`,
    10,
  )
  addLine(
    `Duration: ${report.reportedSymptoms.durationLabel} | Severity: ${report.reportedSymptoms.severityLabel} | Progression: ${report.reportedSymptoms.progressionLabel}`,
    10,
  )
  if (report.healthMeasurements.hasAnyValidMeasurement) {
    addLine('Self-Entered Measurements (Unverified):', 10, true)
    for (const m of report.healthMeasurements.items) {
      addLine(`• ${m.label}: ${m.readingText} (${m.verificationTag})`, 10)
    }
  }
  y += 8

  if (mlPredictions.length > 0) {
    addLine('3. Prototype ML Symptom-Pattern Associations (Demo Data Only)', 12, true, [15, 82, 186])
    addLine(
      'Note: Generated by a prototype classifier trained on a synthetic demo dataset — NOT clinically validated and NOT a medical diagnosis.',
      9,
      false,
      [100, 116, 139],
    )
    for (const pred of mlPredictions) {
      const overlap =
        pred.confidencePercent >= 65
          ? 'Strong overlap'
          : pred.confidencePercent >= 30
            ? 'Moderate overlap'
            : 'Possible overlap'
      addLine(
        `• ${pred.condition} — ${overlap} (Specialist: ${pred.recommendedSpecialist})`,
        10,
        true,
      )
      addLine(
        `  Influencing symptoms: ${pred.influencingSymptoms.map((s) => s.label).join(', ')}`,
        9,
      )
    }
    y += 8
  }

  addLine('4. Recommended Next Steps', 12, true, [23, 75, 66])
  for (const step of report.whatYouCanDoNext) {
    addLine(`• ${step}`, 10)
  }
  y += 8

  addLine('5. Emergency Warning Signs (Call 112)', 12, true, [180, 55, 46])
  for (const sign of report.warningSigns) {
    addLine(`• ${sign}`, 10)
  }
  y += 8

  addLine(`Disclaimer: ${report.disclaimer}`, 9, true, [23, 75, 66])

  doc.save(`VITALORA-Health-Report-${new Date().toISOString().slice(0, 10)}.pdf`)
}
